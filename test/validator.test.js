process.on('beforeExit', (code) => process.exit(code || 0));

const test = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const fs = require('fs');

const PDFValidator = require('../src/core/validator/pdf-validator');
const CLSIEngine = require('../src/core/compiler/clsi-engine');

test('PDFValidator - handles missing file', () => {
  const result = PDFValidator.validate('/tmp/nonexistent_file_12345.pdf');
  assert.strictEqual(result.valid, false);
  assert.strictEqual(result.errors.length, 1);
  assert.match(result.errors[0], /does not exist/);
});

test('PDFValidator - detects invalid header and corrupted EOF', () => {
  const dummyPath = '/tmp/fake_doc.pdf';
  fs.writeFileSync(dummyPath, 'Not a real PDF file contents', 'utf-8');
  const result = PDFValidator.validate(dummyPath);
  assert.strictEqual(result.valid, false);
  assert.ok(result.errors.some(e => e.includes('%PDF-')));
  assert.ok(result.errors.some(e => e.includes('%%EOF')));
  fs.unlinkSync(dummyPath);
});

test('PDFValidator - validates real PDF generated by Tectonic', async () => {
  const tmpDir = '/tmp/test_pdf_validator_' + Date.now();
  fs.mkdirSync(tmpDir, { recursive: true });

  const texContent = [
    '\\documentclass{article}',
    '\\begin{document}',
    'Hello AgenticLeaf PDF Validation',
    '\\textbf{Architecture} and \\textit{Performance}',
    '\\end{document}'
  ].join('\n');

  fs.writeFileSync(path.join(tmpDir, 'main.tex'), texContent, 'utf-8');

  const engine = new CLSIEngine();
  const compileRes = await engine.compile(tmpDir, { rootResourcePath: 'main.tex' });
  assert.strictEqual(compileRes.status, 'success');
  assert.ok(compileRes.pdfPath);

  const validReport = PDFValidator.validate(compileRes.pdfPath, {
    targetPageCount: 1,
    requiredKeywords: ['AgenticLeaf', 'Architecture']
  });

  assert.strictEqual(validReport.valid, true);
  assert.strictEqual(validReport.pageCount, 1);
  assert.ok(validReport.sizeBytes > 500);
  assert.strictEqual(validReport.missingKeywords.length, 0);
  assert.ok(validReport.foundKeywords.includes('AgenticLeaf'));

  // Test keyword mismatch
  const missingReport = PDFValidator.validate(compileRes.pdfPath, {
    requiredKeywords: ['NonExistentTermXYZ']
  });
  assert.strictEqual(missingReport.valid, false);
  assert.ok(missingReport.missingKeywords.includes('NonExistentTermXYZ'));

  fs.rmSync(tmpDir, { recursive: true, force: true });
});
